"""Addresses and constants for pokeemerald (BPEE), from emerald/data/bpee.json.

The JSON is generated by tools/gen_emerald_data.py from the pret decomp and its symbol
file. It holds only addresses, enum values, names and the text encoding.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

DATA_FILE = Path(__file__).resolve().parent / "data" / "bpee.json"

MAP_OFFSET = 7  # map buffer coordinates = map coordinates + 7 (include/fieldmap.h)

DIR_NONE, DIR_SOUTH, DIR_NORTH, DIR_WEST, DIR_EAST = 0, 1, 2, 3, 4
DIR_NAMES = {DIR_NONE: "none", DIR_SOUTH: "south", DIR_NORTH: "north", DIR_WEST: "west", DIR_EAST: "east"}
DIR_VECTORS = {DIR_SOUTH: (0, 1), DIR_NORTH: (0, -1), DIR_WEST: (-1, 0), DIR_EAST: (1, 0)}
DIR_BY_NAME = {v: k for k, v in DIR_NAMES.items()}

AVATAR_ON_FOOT, AVATAR_MACH_BIKE, AVATAR_ACRO_BIKE = 1 << 0, 1 << 1, 1 << 2
AVATAR_SURFING, AVATAR_UNDERWATER, AVATAR_CONTROLLABLE = 1 << 3, 1 << 4, 1 << 5
AVATAR_FORCED_MOVE, AVATAR_DASH = 1 << 6, 1 << 7

# include/global.fieldmap.h, MAPGRID_*
GRID_METATILE_MASK, GRID_COLLISION_MASK, GRID_ELEVATION_SHIFT = 0x03FF, 0x0C00, 12
GRID_UNDEFINED = 0x03FF
NUM_METATILES_IN_PRIMARY, NUM_METATILES_TOTAL = 512, 1024
ELEVATION_TRANSITION, ELEVATION_DEFAULT, ELEVATION_MULTI_LEVEL = 0, 3, 15

OBJECT_EVENTS_COUNT, OBJECT_EVENT_SIZE = 16, 0x24
NUM_TASKS, TASK_SIZE = 16, 0x28
TEXT_PRINTER_SIZE = 0x24
SCRIPT_CONTEXT_RUNNING, SCRIPT_CONTEXT_WAITING, SCRIPT_CONTEXT_SHUTDOWN = 0, 1, 2
MSGBOX_HIDDEN = 0


class EmeraldData:
    def __init__(self, raw: dict):
        self.raw = raw
        self.sym: dict[str, int] = {k: v["addr"] for k, v in raw["symbols"].items()}
        self.const: dict[str, int] = raw["constants"]
        self.mb: dict[str, int] = raw["metatile_behaviors"]
        self.mb_names: dict[int, str] = {v: k for k, v in self.mb.items()}
        self.surfable: frozenset[int] = frozenset(raw["surfable_behaviors"])
        self.encounter: frozenset[int] = frozenset(raw["encounter_behaviors"])
        self.gfx_names: dict[int, str] = {v: k for k, v in raw["object_gfx"].items()}
        self.maps: dict[tuple[int, int], str] = {
            tuple(int(p) for p in k.split(".")): v for k, v in raw["maps"].items()}
        self.map_ids: dict[str, tuple[int, int]] = {v: k for k, v in self.maps.items()}
        self.charmap: dict[int, str] = {int(k, 16): v for k, v in raw["charmap"].items()}
        # code address -> name, for naming gMain.callback2 and task funcs
        self.code_names: dict[int, str] = {a: n for n, a in self.sym.items() if 0x08000000 <= a < 0x0A000000}

    def map_name(self, group: int, num: int) -> str:
        return self.maps.get((group, num), f"MAP_{group}_{num}")

    def code_name(self, addr: int) -> str:
        return self.code_names.get(addr & ~1, f"{addr:#010x}")


@lru_cache(maxsize=None)
def load(path: str | None = None) -> EmeraldData:
    return EmeraldData(json.loads(Path(path or DATA_FILE).read_text(encoding="utf-8")))
